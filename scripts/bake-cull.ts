// Works out, for every tile of every chapter a camera can be in, which scenery is in sight from it
// (client/src/cull.ts), and writes the tables to client/src/pvs/. No browser: the world is built
// against a stand-in for WebGL. Run it after changing a map, or what the world builders draw; a
// stale table is never used (cull.ts checks it against the geometry at load, and `npm run check:cull`
// fails on one). Takes a minute or two per chapter; without an argument the chapters run side by side.
// Usage: npm run bake:cull [chapterIndex]
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const only = process.argv[2] !== undefined ? Number(process.argv[2]) : -1;
if (only < 0) {
  const { chapterCount } = await import('../shared/chapters');
  const codes = await Promise.all(Array.from({ length: chapterCount() }, (_, i) => new Promise<number>((done) => {
    spawn(process.execPath, [...process.execArgv, process.argv[1], String(i)], { stdio: 'inherit' }).on('exit', (code) => done(code ?? 1));
  })));
  process.exit(codes.some((c) => c !== 0) ? 1 : 0);
}

process.env.CULL = 'live'; // (not from the table that is being replaced)
await import('./headless');
const { getLevel } = await import('../shared/chapters');
const { buildWorld } = await import('../client/src/world');

const L = getLevel(only), id = L.def.id, began = Date.now();
const world = buildWorld(L);
let last = 0;
const data = world.cull.bake((done, of) => {
  if (Date.now() - last < 15000) return;
  last = Date.now();
  console.log(`${id}: ${done}/${of} tiles`);
});
const file = fileURLToPath(new URL(`../client/src/pvs/${id}.ts`, import.meta.url));
const text = data ? Buffer.from(data).toString('base64') : '';
writeFileSync(file, `// Generated by \`npm run bake:cull\` (scripts/bake-cull.ts). Do not edit.\nexport default '${text}';\n`);
console.log(`${id}: ${data ? `${(data.length / 1024).toFixed(0)} KB` : 'a flat map: nothing to bake'}, ${((Date.now() - began) / 1000).toFixed(0)} s -> client/src/pvs/${id}.ts`);
world.dispose();
process.exit(0);
